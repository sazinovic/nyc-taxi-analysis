"""Generate a reviewable numerical report directly from the validated summary."""
import argparse
from pathlib import Path
import pandas as pd
from nyc_taxi.comparison import compare_periods
from nyc_taxi.config import DEFAULT_CONFIG
from nyc_taxi.validation import validate_monthly_summary


def main():
    root = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--summary", type=Path, default=Path.home() / "Data/processed/nyc-taxi/monthly_summary.parquet")
    parser.add_argument("--output", type=Path, default=root / "reports/results.md")
    args = parser.parse_args()
    df = pd.read_parquet(args.summary)
    validate_monthly_summary(df, "2015-01", "2026-08")
    if not df.processing_fingerprint.eq(DEFAULT_CONFIG.fingerprint).all():
        raise ValueError("Report expects the default analysis configuration")
    comparison = compare_periods(df)
    rows = ["# NYC Yellow Taxi Analysis Results", "", "Generated by `scripts/generate_results.py` from the validated monthly summary. All cross-year comparisons below cover January–August. This file can be regenerated after processing changes.", "",
            f"- Monthly observations: **{len(df)}**", f"- Raw source records: **{int(df.raw_record_count.sum()):,}**",
            f"- In-period records: **{int(df.trip_count.sum()):,}**", f"- Outside nominal month: **{int(df.outside_period_count.sum()):,}**",
            f"- Processing fingerprint: `{DEFAULT_CONFIG.fingerprint}`", "", "## Comparable seasonal windows", "",
            "Median rows are arithmetic averages of monthly medians, not pooled trip-level medians. Share rows aggregate numerators and denominators before division. Average monthly trip counts are rounded to the nearest whole record for display; all calculations use unrounded values.", "",
            "| Metric | 2015 Jan–Aug | 2019 Jan–Aug | 2026 Jan–Aug |", "|---|---:|---:|---:|"]
    labels = {
        "average_monthly_trips": "Average monthly recorded trips",
        "average_monthly_median_duration_min": "Average monthly median duration (min)",
        "average_monthly_median_distance_mi": "Average monthly median distance (mi)",
        "average_monthly_median_speed_mph": "Average monthly median speed (mph)",
        "average_monthly_median_total_amount": "Average monthly median recorded amount (USD)",
        "average_monthly_valid_monetary_total_amount_sum": "Average monthly selected monetary sum (USD)",
        "airport_pickup_share": "Airport share among known pickup zones (%)",
        "credit_card_share": "Credit-card share of all in-period records (%)",
        "nonflex_credit_card_share": "Credit-card share among codes 1–4 (%)",
        "flex_fare_share": "Flex Fare share of all in-period records (%)",
    }
    for metric, label in labels.items():
        if metric == "average_monthly_trips":
            display_format = ",.0f"
        elif metric == "average_monthly_median_distance_mi":
            display_format = ",.3f"
        else:
            display_format = ",.2f"
        rows.append(f"| {label} | " + " | ".join(format(comparison.loc[year, metric], display_format) for year in comparison.index) + " |")
    rows.extend(["", "## Changes from 2019 to 2026", ""])
    for metric in list(labels)[:6]:
        before, after = comparison.loc[2019, metric], comparison.loc[2026, metric]
        rows.append(f"- {labels[metric]}: **{(after / before - 1) * 100:+.2f}%**.")
    indexed = df.set_index(["year", "month"])
    peak, low = df.loc[df.trip_count.idxmax()], df.loc[df.trip_count.idxmin()]
    apr_change = (indexed.loc[(2020, 4), "trip_count"] / indexed.loc[(2019, 4), "trip_count"] - 1) * 100
    rows.extend(["", "## Historical activity", "",
                 f"- Peak: {int(peak.year)}-{int(peak.month):02d}, {int(peak.trip_count):,} records.",
                 f"- Low: {int(low.year)}-{int(low.month):02d}, {int(low.trip_count):,} records.",
                 f"- Historical peak-to-low change: {(low.trip_count / peak.trip_count - 1) * 100:.2f}%.",
                 f"- April 2020 versus April 2019: {apr_change:.2f}% (same calendar month).",
                 "", "## January 2026 monetary reconciliation", ""])
    january = indexed.loc[(2026, 1)]
    january_metrics = [
        ("monetary_valid_count", "Records included in monetary analysis"),
        ("monetary_excluded_count", "Records excluded from monetary analysis"),
        ("valid_monetary_total_amount_sum", "Selected recorded total amount (USD)"),
        ("finite_signed_total_amount_sum", "All finite recorded totals, including negatives (USD)"),
        ("excluded_monetary_total_amount_sum", "Finite recorded totals excluded by the monetary filter (USD)"),
        ("monetary_outlier_count", f"Records with finite total above ${DEFAULT_CONFIG.monetary_alert_usd:,.0f}"),
        ("monetary_outlier_amount_sum", "Selected recorded total amount above the alert threshold (USD)"),
        ("max_valid_total_amount", "Largest selected recorded total amount (USD)"),
        ("pickup_zone_unknown_count", "Records with unknown pickup zone"),
    ]
    rows.extend(["| Metric | Value |", "|---|---:|"])
    for column, label in january_metrics:
        value = f"{int(january[column]):,}" if column.endswith("_count") else f"{january[column]:,.2f}"
        rows.append(f"| {label} | {value} |")
    rows.extend(["", "Selected amounts exclude negative, nonfinite and inconsistent records. Finite signed totals include either sign. These are descriptive recorded aggregates, not net revenue. Positive amounts above the alert threshold remain included when they pass the monetary filter. The alert count covers all finite in-period totals above the threshold; the alert amount sum covers only monetary-valid records.",
                 "", f"## Coverage across {len(df)} monthly observations", "", "| Analysis | Minimum monthly coverage (%) | Maximum monthly coverage (%) |", "|---|---:|---:|"])
    coverage_labels = {
        "duration": "Trip duration",
        "distance": "Trip distance",
        "speed": "Calculated trip speed",
        "monetary": "Recorded monetary amounts",
        "passenger": "Passenger count",
        "ratecode": "Standard rate code",
    }
    for name, label in coverage_labels.items():
        values = df[f"{name}_coverage_pct"]
        rows.append(f"| {label} | {values.min():.3f} | {values.max():.3f} |")
    rows.extend(["", "## Interpretation", "", "Observed records describe Yellow Taxi activity, not all NYC travel or unmet passenger demand. Different metrics use different selected records. Changing coverage, route/vendor mix, payment categories and analytical windows may influence trends. Monetary values are nominal. The sensitivity notebook checks January 2026 only. No causal effect or pooled multi-month median is inferred.", ""])
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(rows))
    print(f"Generated {args.output}")


if __name__ == "__main__":
    main()
